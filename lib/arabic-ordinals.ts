// موديول 4 — ترقيم عربي بالحروف ("أولاً"، "ثانياً"، ...) لعناوين الأقسام
// الرئيسية في التقرير القضائي، مصدر وحيد تستخدمه الواجهة (لوحة الاعتراضات،
// أكورديون المهام) وتصدير Word معاً، حتى لا يختلف الترقيم المعروض على
// الشاشة عن الترقيم في الملف المُصدَّر. مصحَّح عن التقرير المرجعي: ذاك كرَّر
// "سادساً" لقسمي التصفية والعرض على الأطراف (خطأ كتابي في المصدر الأصلي)؛
// هنا تسلسل نظيف من تسعة عناوين بلا تكرار.
const ARABIC_ORDINALS = [
  "أولاً",
  "ثانياً",
  "ثالثاً",
  "رابعاً",
  "خامساً",
  "سادساً",
  "سابعاً",
  "ثامناً",
  "تاسعاً",
  "عاشراً",
  "حادي عشر",
  "ثاني عشر",
] as const;

/** يعيد الترقيم العربي بالحروف لفهرس صفري (0 ⇒ "أولاً"). فهرس يتجاوز
 * القائمة الثابتة (حالة نادرة جداً لتقرير بأكثر من 12 قسماً رئيسياً) يعود
 * إلى ترقيم رقمي بسيط بدل الانهيار أو تكرار آخر عنصر. */
export function arabicOrdinal(index0: number): string {
  return ARABIC_ORDINALS[index0] ?? `(${index0 + 1})`;
}
